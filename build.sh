#!/usr/bin/env bash
# The lark build. The Makefile is a copy of the convention kit and holds only the
# kit gates. This script holds the tasks that only lark has.
#
#   ./build.sh bootstrap    fetch modules. go.mod and go.sum carry every pin.
#   ./build.sh generate     regenerate proto/gen from proto/
#   ./build.sh build        compile every package
#   ./build.sh binaries     bin/lark.bin and bin/lark-clock.bin
#   ./build.sh lint-proto   buf lint on the hand-written schemas
#   ./build.sh lint-banner  the generated banner is the first line
#   ./build.sh check        lint-proto and lint-banner
#   ./build.sh clean        remove proto/gen and bin
#
# Do `make check` and `./build.sh check` before a change closes.

set -euo pipefail

GO="${GO:-go}"
BANNER='^// Code generated by .* DO NOT EDIT\.$'

cd "$(dirname "$0")"

bootstrap() {
	"$GO" mod download
}

generate() {
	"$GO" tool buf generate
}

build() {
	"$GO" build ./...
}

binaries() {
	mkdir -p bin
	"$GO" build -o bin/lark.bin ./cmd/lark
	"$GO" build -o bin/lark-clock.bin ./cmd/clock
}

lint_proto() {
	echo "==> buf lint"
	"$GO" tool buf lint
}

lint_banner() {
	local bad=""
	local file

	echo "==> banner"
	while IFS= read -r file; do
		if ! head -1 "$file" | grep -q "$BANNER"; then
			bad+="$file"$'\n'
		fi
	done < <(find proto/gen -name '*.go' -print)

	if [ -n "$bad" ]; then
		echo "generated files whose first line is not the banner:"
		printf '%s' "$bad"
		exit 1
	fi
}

check() {
	lint_proto
	lint_banner
}

clean() {
	rm -rf proto/gen bin
}

usage() {
	sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'
}

case "${1:-}" in
	bootstrap) bootstrap ;;
	generate) generate ;;
	build) build ;;
	binaries) binaries ;;
	lint-proto) lint_proto ;;
	lint-banner) lint_banner ;;
	check) check ;;
	clean) clean ;;
	*)
		usage
		exit 2
		;;
esac
