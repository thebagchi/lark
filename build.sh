#!/usr/bin/env bash
# The lark build. The Makefile is a copy of the convention kit and holds only the
# kit gates. This script holds the tasks that only lark has.
#
#   ./build.sh bootstrap    fetch modules. go.mod and go.sum carry every pin.
#   ./build.sh generate     regenerate proto/gen from proto/
#   ./build.sh build        compile every package
#   ./build.sh binaries     bin/lark.bin and bin/lark-clock.bin
#   ./build.sh lint-proto   buf lint on the hand-written schemas
#   ./build.sh lint-banner  the generated banner is the first line
#   ./build.sh check        lint-proto and lint-banner
#   ./build.sh bench        benchmark v1, add a dated report to benchmark/README.md
#   ./build.sh bench-ab REF compare REF with the working tree, interleaved, with benchstat
#   ./build.sh deadcode     report functions no binary and no test can reach
#   ./build.sh clean        remove proto/gen and bin
#
# Do `make check` and `./build.sh check` before a change closes.

set -euo pipefail

GO="${GO:-go}"
BANNER='^// Code generated by .* DO NOT EDIT\.$'

# bench keeps each run's raw output in BENCH_DIR, so benchstat can read any two
# of them later, and adds the summary of the run to BENCH_REPORT. The report sits
# in BENCH_DIR, so the raw files are next to it.
BENCH_DIR=benchmark
BENCH_REPORT="$BENCH_DIR/README.md"
BENCH_COUNT="${BENCH_COUNT:-6}"
BENCH_PKGS="${BENCH_PKGS:-./v1/...}"

# bench-ab keeps the raw files of each comparison in AB_DIR/<date>/, one old.txt
# and one new.txt. benchstat advises at least 10 runs per side, so AB_ROUNDS
# defaults to 10. Each round runs every package once on each side.
AB_DIR="$BENCH_DIR/ab"
AB_ROUNDS="${AB_ROUNDS:-10}"
AB_TMP=""

cd "$(dirname "$0")"

bootstrap() {
	"$GO" mod download
}

generate() {
	"$GO" tool buf generate
}

build() {
	"$GO" build ./...
}

binaries() {
	mkdir -p bin
	"$GO" build -o bin/lark.bin ./cmd/lark
	"$GO" build -o bin/lark-clock.bin ./cmd/clock
}

lint_proto() {
	echo "==> buf lint"
	"$GO" tool buf lint
}

lint_banner() {
	local bad=""
	local file

	echo "==> banner"
	while IFS= read -r file; do
		if ! head -1 "$file" | grep -q "$BANNER"; then
			bad+="$file"$'\n'
		fi
	done < <(find proto/gen -name '*.go' -print)

	if [ -n "$bad" ]; then
		echo "generated files whose first line is not the banner:"
		printf '%s' "$bad"
		exit 1
	fi
}

check() {
	lint_proto
	lint_banner
}

# bench runs every benchmark under BENCH_PKGS BENCH_COUNT times and adds one
# dated section to BENCH_REPORT, then refreshes the package list in it. The
# section holds the command, the machine, the commit and the benchstat summary
# of this run alone. Two dated sections are not a comparison: runs taken hours
# apart differ for reasons that are not the code, so a before/after claim needs
# both sides run together.
bench() {
	local stamp="$(date +%Y-%m-%d-%H%M%S)"
	local raw="$BENCH_DIR/$stamp.txt"
	local command="$GO test -run '^\$' -bench . -benchmem -count $BENCH_COUNT $BENCH_PKGS"

	mkdir -p "$BENCH_DIR"
	echo "==> $command"
	"$GO" test -run '^$' -bench . -benchmem -count "$BENCH_COUNT" $BENCH_PKGS | tee "$raw"

	if [ ! -f "$BENCH_REPORT" ]; then
		bench_header >"$BENCH_REPORT"
	fi
	bench_section "$stamp" "$raw" "$command" >>"$BENCH_REPORT"
	bench_refresh_index
	echo "==> added $stamp to $BENCH_REPORT"
}

bench_header() {
	cat <<-EOF
	# Benchmarks

	Dated reports from \`./build.sh bench\`, oldest first. Each section is one run.
	The raw output of each run sits next to this file, named by its date.

	Do not compare two sections to claim a speed-up. Runs taken hours apart
	differ for reasons that are not the code. To compare, run both sides
	together and give both raw files to benchstat:

	    go tool benchstat $BENCH_DIR/<before>.txt $BENCH_DIR/<after>.txt

	$(bench_index)
	EOF
}

# bench_index prints the "Package reports" section: one link for each package
# report in BENCH_DIR. A report is a file named v1-*.md, the package path with
# slashes as dashes. The order is the byte order of the names.
bench_index() {
	local file name title

	echo "## Package reports"
	echo
	echo "Each accepted change that claims a speedup adds a row to the report of its package."
	echo "The file name is the package path with slashes as dashes."
	echo "\`./build.sh bench\` regenerates this list from the files present."
	echo
	for file in $(LC_ALL=C; echo "$BENCH_DIR"/v1-*.md); do
		if [ -e "$file" ]; then
			name="${file##*/}"
			title="${name%.md}"
			echo "- [${title//-//}](${name})"
		fi
	done
}

# bench_refresh_index rewrites the "Package reports" section of BENCH_REPORT in
# place, from the section heading to the next "## " heading. It adds the section
# before the first dated section when the report has none. The dated sections
# stay as they are.
bench_refresh_index() {
	local index="$BENCH_REPORT.index" next="$BENCH_REPORT.next"

	bench_index >"$index"
	awk -v idx="$index" '
		BEGIN { while ((getline line < idx) > 0) gen = gen line "\n" }
		/^## Package reports$/ { printf "%s\n", gen; skip = 1; done = 1; next }
		/^## / { if (skip) skip = 0; else if (!done) { printf "%s\n", gen; done = 1 } }
		skip { next }
		{ print }
		END { if (!done) printf "\n%s", gen }
	' "$BENCH_REPORT" >"$next"
	mv "$next" "$BENCH_REPORT"
	rm -f "$index"
}

bench_section() {
	local stamp="$1" raw="$2" command="$3"
	local name="${raw##*/}"
	local state="clean"

	if [ -n "$(git status --porcelain)" ]; then
		state="with uncommitted changes"
	fi

	cat <<-EOF

	## $stamp

	- Command: \`$command\`
	- Commit: $(git rev-parse --short HEAD), $state
	- Go: $("$GO" env GOVERSION) $("$GO" env GOOS)/$("$GO" env GOARCH)
	- CPU: $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2 | sed 's/^ //'), $(nproc) logical CPUs
	- Kernel: $(uname -r)
	- Raw: \`$name\`

	\`\`\`
	$(cd "$BENCH_DIR" && "$GO" tool benchstat "$name")
	\`\`\`
	EOF
}

# bench_ab compares git ref REF (old) with the working tree (new). It builds one
# test binary per package on each side, then runs old and new alternately for
# AB_ROUNDS rounds, so drift in the host hits both sides. It prints the benchstat
# comparison to stdout. It does not write BENCH_REPORT: bench records history,
# bench-ab makes claims. REF is checked out in a temporary git worktree, so the
# working tree stays as it is. The EXIT trap removes the worktree.
bench_ab() {
	local ref="${1:-}"
	local commit stamp out line rel round
	local -a rels=()

	if [ -z "$ref" ]; then
		echo "bench-ab: a git ref is required, for example: ./build.sh bench-ab HEAD" >&2
		exit 2
	fi
	if ! commit="$(git rev-parse --verify --quiet "$ref^{commit}")"; then
		echo "bench-ab: '$ref' is not a git ref that names a commit" >&2
		exit 2
	fi

	case "$AB_ROUNDS" in
		'' | *[!0-9]* | 0*)
			echo "bench-ab: AB_ROUNDS must be a positive integer, got '$AB_ROUNDS'" >&2
			exit 2
			;;
	esac
	if [ -z "${BENCH_PKGS//[[:space:]]/}" ]; then
		echo "bench-ab: BENCH_PKGS is empty" >&2
		exit 2
	fi

	AB_TMP="$(mktemp -d)"
	trap bench_ab_cleanup EXIT
	git worktree add --detach --quiet "$AB_TMP/ref" "$commit"

	stamp="$(date +%Y-%m-%d-%H%M%S)"
	out="$AB_DIR/$stamp"
	mkdir -p "$out"

	# One line per package: the directory relative to the repository root.
	while IFS= read -r line; do
		rels+=("${line#"$PWD"}")
	done < <("$GO" list -f '{{.Dir}}' $BENCH_PKGS)

	echo "==> building test binaries for $ref ($(git rev-parse --short "$commit")) and the working tree"
	local -a built=()
	for rel in "${rels[@]}"; do
		rel="./${rel#/}"
		if bench_ab_build "$rel"; then
			built+=("$rel")
		fi
	done
	if [ "${#built[@]}" -eq 0 ]; then
		echo "bench-ab: no package in '$BENCH_PKGS' has benchmarks that build on both sides" >&2
		exit 1
	fi

	for round in $(seq "$AB_ROUNDS"); do
		echo "==> round $round of $AB_ROUNDS"
		for rel in "${built[@]}"; do
			bench_ab_run old "$rel" "$round" "$AB_TMP/ref/$rel" "$out/old.txt"
			bench_ab_run new "$rel" "$round" "$PWD/$rel" "$out/new.txt"
		done
	done

	if ! grep -q '^Benchmark' "$out/old.txt" || ! grep -q '^Benchmark' "$out/new.txt"; then
		echo "bench-ab: no benchmark output in '$BENCH_PKGS'; nothing to compare" >&2
		exit 1
	fi

	echo "==> go tool benchstat $out/old.txt $out/new.txt"
	"$GO" tool benchstat "$out/old.txt" "$out/new.txt"
}

# bench_ab_name turns a package path such as ./v1/a into a file name, v1_a.
bench_ab_name() {
	local name="${1#./}"

	name="${name//\//_}"
	echo "${name:-root}"
}

# bench_ab_build builds the old and the new test binary of one package. It
# returns 1 and prints a skip line when the package does not exist in REF or has
# no test files. A compiler failure on either side ends the whole run with exit
# 1, so a comparison never covers fewer packages than asked without saying so.
# The function exits itself because callers test its status in an "if", where
# "set -e" is off.
bench_ab_build() {
	local rel="$1"
	local name

	name="$(bench_ab_name "$rel")"
	mkdir -p "$AB_TMP/old" "$AB_TMP/new"
	if [ ! -d "$AB_TMP/ref/$rel" ]; then
		echo "    skipped: $rel is not in the old ref"
		return 1
	fi
	if ! "$GO" test -c -o "$AB_TMP/new/$name.test" "$rel"; then
		echo "bench-ab: build failed on the working tree side for $rel" >&2
		exit 1
	fi
	if ! (cd "$AB_TMP/ref" && "$GO" test -c -o "$AB_TMP/old/$name.test" "$rel"); then
		echo "bench-ab: build failed on the old ref side for $rel" >&2
		exit 1
	fi
	if [ ! -f "$AB_TMP/new/$name.test" ] || [ ! -f "$AB_TMP/old/$name.test" ]; then
		echo "    skipped: $rel has no test files on one side"
		return 1
	fi
}

# bench_ab_run runs the test binary of package REL once, on SIDE (old or new),
# in directory DIR, as "go test" would, so that relative paths in the tests
# resolve. It appends the output to RAW. A non-zero exit ends the whole run with
# exit 1, a message that names the side, the package and the round, and the tail
# of the output, because the output would otherwise go only to RAW.
bench_ab_run() {
	local side="$1" rel="$2" round="$3" dir="$4" raw="$5"
	local bin="$AB_TMP/$side/$(bench_ab_name "$rel").test"
	local log="$AB_TMP/run.log"

	if ! (cd "$dir" && "$bin" -test.run '^$' -test.bench . -test.benchmem -test.count 1) >"$log" 2>&1; then
		echo "bench-ab: benchmark run failed on the $side side for $rel in round $round; last lines:" >&2
		tail -n 20 "$log" >&2
		exit 1
	fi
	cat "$log" >>"$raw"
}

bench_ab_cleanup() {
	if [ -n "$AB_TMP" ]; then
		git worktree remove --force "$AB_TMP/ref" 2>/dev/null || true
		rm -rf "$AB_TMP"
		git worktree prune
	fi
}

# deadcode reports functions that no main package and no test can reach. The
# roots are every main package and every test in the module: with -test, a
# function that only a test calls counts as live. Without -test the report also
# lists the exported API that only the library users call, which is noise here.
# deadcode exits 0 when it finds something, so this task only reports and does
# not gate. Judge each line before deleting it: a dead method can still be
# needed to satisfy an interface.
deadcode() {
	echo "==> go tool deadcode -test ./..."
	"$GO" tool deadcode -test ./...
}

clean() {
	rm -rf proto/gen bin
}

usage() {
	sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'
}

case "${1:-}" in
	bootstrap) bootstrap ;;
	generate) generate ;;
	build) build ;;
	binaries) binaries ;;
	lint-proto) lint_proto ;;
	lint-banner) lint_banner ;;
	check) check ;;
	bench) bench ;;
	bench-ab) bench_ab "${2:-}" ;;
	deadcode) deadcode ;;
	clean) clean ;;
	*)
		usage
		exit 2
		;;
esac
